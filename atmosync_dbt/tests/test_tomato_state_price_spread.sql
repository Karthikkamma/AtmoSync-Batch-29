SELECT *
FROM {{ ref('tomato_state_price_spread') }}
WHERE STATE IS NULL
   OR MARKET_COUNT IS NULL
   OR MARKET_COUNT < 2
   OR LOWEST_PRICE IS NULL
   OR HIGHEST_PRICE IS NULL
   OR STATE_PRICE_SPREAD IS NULL
   OR LOWEST_PRICE < 100
   OR HIGHEST_PRICE < LOWEST_PRICE
   OR STATE_PRICE_SPREAD < 0
   OR ABS(STATE_PRICE_SPREAD -
       (HIGHEST_PRICE - LOWEST_PRICE)) > 0.000001
       