SELECT
    CONTAINER_ID,
    COUNT(*) AS TOTAL_READINGS,
    ROUND(AVG(TEMPERATURE_C), 2) AS AVG_TEMPERATURE_C,
    ROUND(MAX(TEMPERATURE_C), 2) AS MAX_TEMPERATURE_C,
    ROUND(AVG(HUMIDITY_PERCENT), 2) AS AVG_HUMIDITY_PERCENT,
    MIN(EVENT_TIMESTAMP) AS FIRST_READING_AT,
    MAX(EVENT_TIMESTAMP) AS LAST_READING_AT
FROM {{ ref('stg_container_telemetry') }}
GROUP BY CONTAINER_ID
