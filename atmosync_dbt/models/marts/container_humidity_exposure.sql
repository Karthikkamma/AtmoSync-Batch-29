SELECT
    CONTAINER_ID,
    COUNT(*) AS TOTAL_READINGS,
    COUNT_IF(HUMIDITY_PERCENT > 90) AS READINGS_ABOVE_90_HUMIDITY,
    ROUND(
        100.0 * COUNT_IF(HUMIDITY_PERCENT > 90)
        / NULLIF(COUNT(*), 0),
        2
    ) AS PERCENT_READINGS_ABOVE_90_HUMIDITY,
    ROUND(AVG(HUMIDITY_PERCENT), 2) AS AVG_HUMIDITY_PERCENT
FROM {{ ref('stg_container_telemetry') }}
GROUP BY CONTAINER_ID
