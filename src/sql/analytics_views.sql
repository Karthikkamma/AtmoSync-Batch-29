-- AtmoSync: Agricultural Price Analytics
-- Creates reusable Snowflake analytics views.

-- View 1: Clean agricultural price data
CREATE OR REPLACE VIEW ATMOSYNC_DB.RAW.V_AGRICULTURAL_PRICES AS
SELECT
    RECORD:State::STRING AS STATE,
    RECORD:District::STRING AS DISTRICT,
    RECORD:Market::STRING AS MARKET,
    RECORD:Commodity::STRING AS COMMODITY,
    RECORD:Variety::STRING AS VARIETY,
    RECORD:Grade::STRING AS GRADE,
    TRY_TO_DATE(RECORD:Arrival_Date::STRING) AS ARRIVAL_DATE,
    TRY_TO_DOUBLE(RECORD:Min_Price::STRING) AS MIN_PRICE,
    TRY_TO_DOUBLE(RECORD:Max_Price::STRING) AS MAX_PRICE,
    TRY_TO_DOUBLE(RECORD:Modal_Price::STRING) AS MODAL_PRICE
FROM ATMOSYNC_DB.RAW.AGRICULTURAL_PRICES;


-- View 2: Market arbitrage analysis
CREATE OR REPLACE VIEW ATMOSYNC_DB.RAW.V_MARKET_ARBITRAGE AS
SELECT
    COMMODITY,
    ARRIVAL_DATE,
    COUNT(DISTINCT MARKET) AS TOTAL_MARKETS,
    ROUND(MIN(MODAL_PRICE), 2) AS LOWEST_PRICE,
    ROUND(MAX(MODAL_PRICE), 2) AS HIGHEST_PRICE,
    ROUND(MAX(MODAL_PRICE) - MIN(MODAL_PRICE), 2)
        AS PRICE_DIFFERENCE,
    ROUND(
        (MAX(MODAL_PRICE) - MIN(MODAL_PRICE))
        / NULLIF(MIN(MODAL_PRICE), 0) * 100,
        2
    ) AS PRICE_DIFFERENCE_PERCENT
FROM ATMOSYNC_DB.RAW.V_AGRICULTURAL_PRICES
WHERE MODAL_PRICE > 0
  AND ARRIVAL_DATE IS NOT NULL
GROUP BY COMMODITY, ARRIVAL_DATE
HAVING COUNT(DISTINCT MARKET) > 1;